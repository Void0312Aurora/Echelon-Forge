def test_generated_boundary_verifier_rejects_link_include_source_and_install_drift(
  tmp_path: Path,
) -> None:
  verifier = REPO_ROOT / "cmake" / "verify_runtime_contracts_boundary.cmake"
  expected_include = (tmp_path / "include").as_posix()
  clean_manifest = (
    "type=STATIC_LIBRARY\n"
    "links=\n"
    "interface_links=\n"
    f"includes={expected_include}\n"
    f"interface_includes={expected_include}\n"
    "sources=include/runtime_identity.h|src/runtime_identity.cpp\n"
  )

  cases = {
    "direct_link": (clean_manifest.replace("links=\n", "links=ef_core\n"), "# clean\n"),
    "interface_include": (
      clean_manifest.replace(
        f"interface_includes={expected_include}",
        "interface_includes=D:/private/src",
      ),
      "# clean\n",
    ),
    "source_graph": (
      clean_manifest.replace(
        "sources=include/runtime_identity.h|src/runtime_identity.cpp",
        "sources=src/runtime_identity.cpp|src/ef_facade_adapter.cpp",
      ),
      "# clean\n",
    ),
    "install_graph": (clean_manifest, "# install ef_runtime_contracts\n"),
  }
  for case_name, (manifest_text, install_text) in cases.items():
    manifest = tmp_path / f"{case_name}.manifest.txt"
    install_script = tmp_path / f"{case_name}.install.cmake"
    manifest.write_text(manifest_text, encoding="utf-8")
    install_script.write_text(install_text, encoding="utf-8")
    result = subprocess.run(
      [
        "cmake",
        f"-DMANIFEST={manifest}",
        f"-DINSTALL_SCRIPT={install_script}",
        f"-DEXPECTED_INCLUDE_ROOT={expected_include}",
        "-P",
        str(verifier),
      ],
      cwd=REPO_ROOT,
      check=False,
      capture_output=True,
      text=True,
    )
    assert result.returncode != 0, f"{case_name} drift was accepted"


def test_focused_native_consumer_and_production_graph_remain_separate() -> None:
  cmake = _text(CMAKE)
  source = _text(COMPILE_TEST)

  assert source.startswith("#include <echelon_forge/runtime_contracts/runtime_identity.h>")
  assert "runtime_contracts::v1" in source
  for forbidden in ('"core/', '"components/', '"runtime/facade/'):
    assert forbidden not in source

  target = cmake.split("add_executable(ef_runtime_contracts_compile_test", 1)[1].split(
    ")", 1
  )[0]
  link = cmake.split("target_link_libraries(ef_runtime_contracts_compile_test", 1)[1].split(
    ")", 1
  )[0]
  assert "test_runtime_identity_contracts.cpp" in target
  assert "ef_runtime_contracts" in link
  for forbidden in ("ef_core", "ef_facade", "ef_composition", "flecs", "doctest"):
    assert forbidden not in target
    assert forbidden not in link

  allowed_source_consumers = {
    REPO_ROOT / "src" / "runtime" / "contracts" / "public" / "runtime_identity.cpp",
    REPO_ROOT / "src" / "runtime" / "host" / "runtime_host_candidate.h",
    REPO_ROOT / "src" / "runtime" / "host" / "runtime_state_transfer_candidate.h",
    COMPILE_TEST,
  }
  source_consumers = {
    path
    for path in (REPO_ROOT / "src").rglob("*")
    if path.suffix in {".h", ".hpp", ".cpp", ".cc"}
    and "echelon_forge/runtime_contracts/runtime_identity.h" in _text(path)
  }
  assert source_consumers == allowed_source_consumers


