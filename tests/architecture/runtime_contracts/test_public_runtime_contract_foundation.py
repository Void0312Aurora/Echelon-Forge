from __future__ import annotations

import re
from pathlib import Path
import subprocess

from tools.maintenance.dto_schema.generate import load_schemas
from tools.maintenance.dto_schema.model import DtoSchema, Field
from tools.maintenance.dto_schema.schemas.runtime_contracts import (
  ASCII_FILE_HEADER,
  PUBLIC_RUNTIME_CONTRACT_CPP_TYPES,
  validate_public_runtime_contract_schema,
)


REPO_ROOT = Path(__file__).resolve().parents[3]
PUBLIC_HEADER = (
  REPO_ROOT
  / "include"
  / "echelon_forge"
  / "runtime_contracts"
  / "runtime_identity.h"
)
CMAKE = REPO_ROOT / "CMakeLists.txt"
COMPILE_TEST = REPO_ROOT / "src" / "tests" / "test_runtime_identity_contracts.cpp"
PUBLIC_SCHEMA_PREFIX = "include/echelon_forge/runtime_contracts/detail/"


def _text(path: Path) -> str:
  return path.read_text(encoding="utf-8")


def _public_identity_schemas():
  return tuple(
    schema
    for _, schema in load_schemas()
    if schema.output_path.startswith(PUBLIC_SCHEMA_PREFIX)
  )


def test_public_identity_header_is_versioned_and_engine_independent() -> None:
  header = _text(PUBLIC_HEADER)
  includes = re.findall(r'^\s*#\s*include\s+([<"][^>"]+[>"])', header, re.MULTILINE)
  standard_includes = {value for value in includes if value.startswith("<c") or value == "<type_traits>"}
  generated_includes = {
    f"<{schema.output_path.removeprefix('include/')}>"
    for schema in _public_identity_schemas()
  }

  assert standard_includes == {"<cstddef>", "<cstdint>", "<type_traits>"}
  assert generated_includes == set(includes) - standard_includes
  assert "namespace echelon_forge::runtime_contracts::v1" in header
  assert "kRuntimeIdentityContractGeneration = 1" in header

  for forbidden in (
    "components/",
    "core/",
    "runtime/facade/",
    "flecs",
    "nlohmann",
    "nanobind",
    "std::string",
    "std::vector",
    "void *",
  ):
    assert forbidden not in header


def test_registered_schema_is_the_single_public_field_list_owner() -> None:
  header = _text(PUBLIC_HEADER)
  schemas = _public_identity_schemas()
  schema_names = {schema.name for schema in schemas}

  assert schema_names == {
    "runtime_identity_128",
    "runtime_host_identity",
    "runtime_incarnation_ref",
    "runtime_world_ref",
    "runtime_entity_ref",
    "runtime_episode_ref",
    "runtime_request_ref",
    "runtime_result_ref",
  }
  for schema in schemas:
    generated_path = REPO_ROOT / schema.output_path
    assert generated_path.is_file()
    assert "GENERATED by tools/maintenance/dto_schema" in _text(generated_path)
    assert f"<{schema.output_path.removeprefix('include/')}>" in header

  result_schema = next(schema for schema in schemas if schema.name == "runtime_result_ref")
  assert tuple(field.name for field in result_schema.fields) == ("request",)
  assert all(field.name != "result_sequence" for schema in schemas for field in schema.fields)


def test_public_schema_type_allowlist_rejects_raw_pointer_injection() -> None:
  for schema in _public_identity_schemas():
    assert all(
      field.cpp_type in PUBLIC_RUNTIME_CONTRACT_CPP_TYPES
      for field in schema.fields
    )

  malicious = DtoSchema(
    name="malicious_public_pointer",
    output_path="include/echelon_forge/runtime_contracts/detail/malicious.inc",
    fields=(
      Field("engine_address", "void *", "{}", "EF_RUNTIME_MALICIOUS_FIELD"),
    ),
    file_header=ASCII_FILE_HEADER,
    file_footer="\n#undef EF_RUNTIME_MALICIOUS_FIELD\n",
  )
  try:
    validate_public_runtime_contract_schema(malicious)
  except ValueError as exc:
    assert "engine_address:void *" in str(exc)
  else:
    raise AssertionError("public runtime contract accepted a raw pointer field")

  include_injection = DtoSchema(
    name="malicious_public_include",
    output_path="include/echelon_forge/runtime_contracts/detail/malicious.inc",
    fields=(
      Field("identity", "std::uint64_t", "0", "EF_RUNTIME_MALICIOUS_FIELD"),
    ),
    file_header=(
      ASCII_FILE_HEADER
      + '#include "../../../../src/runtime/contracts/world_batch_contracts.h"\n'
    ),
    file_footer="\n#undef EF_RUNTIME_MALICIOUS_FIELD\n",
  )
  try:
    validate_public_runtime_contract_schema(include_injection)
  except ValueError as exc:
    assert "closed ASCII header" in str(exc)
  else:
    raise AssertionError("public runtime contract accepted an include injection")


